// Generates src/generated/ from assets/: the asset manifest, URL and require() maps for web and
// native, and React / React Native components for every logo SVG (SVGO, then SVGR).
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";

import { transform } from "@svgr/core";
import jsx from "@svgr/plugin-jsx";
import { optimize } from "svgo";

import { assetsDirectory, readCatalog } from "../src/catalog/catalog.ts";
import { grids } from "../src/catalog/grid.ts";
import {
  appIconVariants,
  avatarFile,
  illustrationFile,
  objectFile,
  sceneFile,
  textureFile,
} from "../src/catalog/paths.ts";

const generated = join(import.meta.dirname, "../src/generated");
const header = "// Generated by @ome-labs/brand (scripts/generate.ts) from assets/. Do not edit.\n";
const catalog = readCatalog();

rmSync(generated, { recursive: true, force: true });
for (const folder of ["", "web", "native"]) {
  mkdirSync(join(generated, folder), { recursive: true });
}

const write = (file: string, source: string) =>
  writeFileSync(join(generated, file), `${header}${source}`);
const pascal = (name: string) =>
  name.replace(/(^|-)(\w)/g, (_, __, letter: string) => letter.toUpperCase());

// Logos: one component per SVG. viewBox is kept so they scale; width and height come from props.
const logos = readdirSync(join(assetsDirectory, "logo"))
  .filter((file) => file.endsWith(".svg"))
  .toSorted()
  .map((file) => ({ file, component: pascal(file.replace(/\.svg$/, "")) }));

await Promise.all(
  logos.flatMap(({ file, component }) => {
    const source = readFileSync(join(assetsDirectory, "logo", file), "utf8");

    return [false, true].map(async (native) => {
      // Accessibility comes from the Logo wrapper, so the generated SVG carries none; React Native's
      // Svg doesn't take xmlns.
      const svg = optimize(source, {
        multipass: true,
        plugins: [
          "preset-default",
          "removeDimensions",
          "removeTitle",
          { name: "removeAttrs", params: { attrs: ["role", "aria-label"] } },
          ...(native ? (["removeXMLNS"] as const) : []),
        ],
      }).data;

      const code = await transform(
        svg,
        {
          typescript: true,
          jsxRuntime: "automatic",
          titleProp: !native,
          native,
          plugins: [jsx],
          exportType: "named",
          namedExport: component,
        },
        { componentName: component },
      );
      write(
        `${native ? "native" : "web"}/${file.replace(/\.svg$/, ".tsx")}`,
        code.replace(/^export \{ .* as default \};?\n?/m, ""),
      );
    });
  }),
);

for (const platform of ["web", "native"]) {
  const exports = logos.map(
    ({ file, component }) => `export { ${component} } from "./${file.replace(/\.svg$/, ".tsx")}";`,
  );
  write(`${platform}/logos.ts`, `${exports.join("\n")}\n`);
}

// The manifest: every asset with its files (relative to assets/), pixel size and alt text.
const scaled = (grid: { width: number; height: number; scales: Record<"1x" | "2x", number> }) => ({
  width: grid.width * grid.scales["1x"],
  height: grid.height * grid.scales["1x"],
});

const manifest = {
  illustrations: catalog.illustrations.map(({ id, title, group, alt }) => ({
    id,
    title,
    group,
    alt,
    ...scaled(grids.illustrations),
    files: { "1x": illustrationFile(group, id, "1x"), "2x": illustrationFile(group, id, "2x") },
  })),
  spot: catalog.spot,
  textures: catalog.textures.map(({ id, title, use }) => ({
    id,
    title,
    use,
    // Textures sit behind content: they carry no meaning, so they have no alt text.
    alt: "",
    ...scaled(grids.textures),
    files: { "1x": textureFile(id, "1x"), "2x": textureFile(id, "2x") },
  })),
  objects: catalog.objects.map(({ id, title, group, alt }) => ({
    id,
    title,
    group,
    alt,
    width: grids.objects.width,
    height: grids.objects.height,
    file: objectFile(group, id),
  })),
  scenes: catalog.scenes.map(({ id, title, alt }) => ({
    id,
    title,
    alt,
    ...scaled(grids.scenes),
    files: { "1x": sceneFile(id, "1x"), "2x": sceneFile(id, "2x") },
  })),
  avatars: catalog.avatars.map(({ id, title, kind, alt }) => ({
    id,
    title,
    kind,
    alt,
    width: grids.avatars.width,
    height: grids.avatars.height,
    file: avatarFile(kind, id),
  })),
  logos: logos.map(({ file }) => ({
    id: file.replace(/\.svg$/, ""),
    alt: "Ome",
    file: `logo/${file}`,
  })),
  appIcons: appIconVariants.map((variant) => ({
    id: variant,
    alt: "Ome",
    file: `app-icon/${variant}.svg`,
  })),
};

write(
  "manifest.ts",
  `export const manifest = ${JSON.stringify(manifest, null, 2)} as const;

export type IllustrationId = (typeof manifest.illustrations)[number]["id"];
export type TextureId = (typeof manifest.textures)[number]["id"];
export type ObjectId = (typeof manifest.objects)[number]["id"];
export type SpotId = (typeof manifest.spot)[number]["id"];
export type SceneId = (typeof manifest.scenes)[number]["id"];
export type AvatarId = (typeof manifest.avatars)[number]["id"];
export type VaultAvatarId = Extract<(typeof manifest.avatars)[number], { kind: "vault" }>["id"];
export type ProfileAvatarId = Extract<(typeof manifest.avatars)[number], { kind: "profile" }>["id"];
`,
);

// Web: URLs through import.meta.url, which Vite, Next.js and other bundlers turn into hashed assets.
const url = (file: string) => `new URL("../../../assets/${file}", import.meta.url).href`;
write(
  "web/assets.ts",
  `export const illustrationUrls = {
${manifest.illustrations.map((item) => `  "${item.id}": { "1x": ${url(item.files["1x"])}, "2x": ${url(item.files["2x"])} },`).join("\n")}
} as const;

export const textureUrls = {
${manifest.textures.map((item) => `  "${item.id}": { "1x": ${url(item.files["1x"])}, "2x": ${url(item.files["2x"])} },`).join("\n")}
} as const;

export const objectUrls = {
${manifest.objects.map((item) => `  "${item.id}": ${url(item.file)},`).join("\n")}
} as const;

export const sceneUrls = {
${manifest.scenes.map((item) => `  "${item.id}": { "1x": ${url(item.files["1x"])}, "2x": ${url(item.files["2x"])} },`).join("\n")}
} as const;

export const avatarUrls = {
${manifest.avatars.map((item) => `  "${item.id}": ${url(item.file)},`).join("\n")}
} as const;
`,
);

// Native: Metro resolves "name.webp" to name@1x.webp / name@2x.webp by screen density. Objects are
// SVG markup for react-native-svg's SvgXml, since Metro can't require SVG without a transformer.
const asset = (file: string) => `require("../../../assets/${file.replace(/@1x\.webp$/, ".webp")}")`;
write(
  "native/assets.ts",
  `import type { ImageSourcePropType } from "react-native";

declare const require: (path: string) => ImageSourcePropType;

export const illustrationSources = {
${manifest.illustrations.map((item) => `  "${item.id}": ${asset(item.files["1x"])},`).join("\n")}
} as const;

export const textureSources = {
${manifest.textures.map((item) => `  "${item.id}": ${asset(item.files["1x"])},`).join("\n")}
} as const;

export const objectXml = {
${manifest.objects.map((item) => `  "${item.id}": ${JSON.stringify(readFileSync(join(assetsDirectory, item.file), "utf8").trim())},`).join("\n")}
} as const;

export const sceneSources = {
${manifest.scenes.map((item) => `  "${item.id}": ${asset(item.files["1x"])},`).join("\n")}
} as const;

export const avatarXml = {
${manifest.avatars.map((item) => `  "${item.id}": ${JSON.stringify(readFileSync(join(assetsDirectory, item.file), "utf8").trim())},`).join("\n")}
} as const;
`,
);

console.log(
  `brand: ${logos.length} logo components per platform, manifest of ${manifest.illustrations.length + manifest.textures.length + manifest.objects.length + manifest.scenes.length + manifest.avatars.length} assets → src/generated/`,
);
