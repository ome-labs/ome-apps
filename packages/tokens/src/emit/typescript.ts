import type { Theme } from "../source/theme.ts";
import { shadowCss } from "./css-web.ts";
import { nativeFamilies, nativeFamily, nativeMetrics } from "./native-fonts.ts";

/** The values code needs directly, as one plain object (no CSS involved). */
export function tokensObject(theme: Theme) {
  const byUtility = (mode: "light" | "dark") =>
    Object.fromEntries(theme.semantic.map((color) => [color.utility, color[mode]]));

  return {
    color: {
      light: byUtility("light"),
      dark: byUtility("dark"),
      primitive: Object.fromEntries(theme.primitives.map((color) => [color.name, color.hex])),
      // The CSS custom property behind each utility name, for inline styles and SVG attributes.
      variable: Object.fromEntries(theme.semantic.map((color) => [color.utility, color.variable])),
    },
    font: {
      web: Object.fromEntries(
        Object.entries(theme.families).map(([name, stack]) => [name, stack.join(", ")]),
      ),
      native: nativeFamilies,
    },
    text: Object.fromEntries(
      theme.text.map((style) => [
        style.name,
        {
          fontSize: style.size,
          ...nativeMetrics(style),
          fontWeight: style.weight,
          webFamily: style.family,
          nativeFamily: nativeFamily(style),
          uppercase: style.uppercase,
        },
      ]),
    ),
    space: Object.fromEntries(theme.space.map((step) => [step.name, step.px])),
    radius: Object.fromEntries(theme.radius.map((radius) => [radius.name, radius.px])),
    control: Object.fromEntries(theme.control.map((control) => [control.name, control.px])),
    shadow: Object.fromEntries(
      theme.elevation.map((elevation) => {
        // React Native's classic shadow props take one layer; the larger, softer layer reads best.
        const layer = elevation.layers[0];
        return [
          elevation.name,
          {
            css: shadowCss(elevation.layers),
            native: layer && {
              shadowColor: layer.color.replace(
                /rgba\((\d+), (\d+), (\d+), [\d.]+\)/,
                "rgb($1, $2, $3)",
              ),
              shadowOpacity: Number(/([\d.]+)\)$/.exec(layer.color)?.[1] ?? 0),
              shadowRadius: layer.blur.value / 2,
              shadowOffset: { width: layer.offsetX.value, height: layer.offsetY.value },
              elevation: Math.round(layer.blur.value / 4),
            },
          },
        ];
      }),
    ),
    motion: {
      duration: Object.fromEntries(theme.duration.map((duration) => [duration.name, duration.ms])),
      easing: Object.fromEntries(theme.easing.map((easing) => [easing.name, easing.curve])),
      sceneSteps: theme.sceneSteps,
    },
    layout: theme.layout,
  };
}

/** Prints a JSON-like value as a TypeScript literal type, so consumers get exact values. */
function literalType(value: unknown, indent = ""): string {
  if (Array.isArray(value)) {
    return `readonly [${value.map((item) => literalType(item, indent)).join(", ")}]`;
  }

  if (value && typeof value === "object") {
    const inner = `${indent}  `;
    const entries = Object.entries(value).map(
      ([key, item]) => `${inner}readonly ${JSON.stringify(key)}: ${literalType(item, inner)};`,
    );
    return `{\n${entries.join("\n")}\n${indent}}`;
  }

  return JSON.stringify(value);
}

export function tokensModule(theme: Theme): { js: string; dts: string } {
  const object = tokensObject(theme);
  const header =
    "// Generated by @ome-labs/tokens from tokens/*.json: edit the JSON, then run `pnpm build`.";

  return {
    js: `${header}\nexport const tokens = ${JSON.stringify(object, null, 2)};\n`,
    dts: `${header}\nexport declare const tokens: ${literalType(object)};\n\nexport type ColorName = keyof typeof tokens.color.light;\nexport type TextStyleName = keyof typeof tokens.text;\nexport type ThemeName = "light" | "dark";\n`,
  };
}
